package reporter

import (
	"fmt"
	"os"
	"strings"

	"redirx/internal/config"
	"redirx/internal/models"
)

// GenerateReports handles output path resolution, overwrite validation, and
// disk serialization for all selected formats (txt, html, json).
func GenerateReports(
	summary models.ScanSummary,
	findings []models.Finding,
	cfg *models.ScanConfig,
	dirs *config.AppDirs,
) ([]string, error) {
	formats := cfg.Formats
	if len(formats) == 0 {
		formats = []string{"txt"}
	}

	scanName := cfg.ResultName
	autoGenerated := false
	if scanName == "" {
		scanName = config.GenerateDefaultName()
		autoGenerated = true
	}

	var generatedPaths []string

	for _, fmtStr := range formats {
		fmtStr = strings.ToLower(strings.TrimSpace(fmtStr))
		if fmtStr == "" {
			continue
		}

		targetPath, err := config.ResolveOutputPath(
			scanName,
			fmtStr,
			cfg.OutputPath,
			dirs.Results,
			cfg.Force,
			cfg.Interactive,
			autoGenerated,
		)
		if err != nil {
			return generatedPaths, fmt.Errorf("failed resolving path for %s report: %w", fmtStr, err)
		}

		file, err := os.OpenFile(targetPath, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0644)
		if err != nil {
			return generatedPaths, fmt.Errorf("failed creating report file %s: %w", targetPath, err)
		}

		var writeErr error
		switch fmtStr {
		case "txt", "text":
			writeErr = WriteTextReport(file, summary, findings)
		case "json":
			writeErr = WriteJSONReport(file, summary, findings)
		case "html", "htm":
			writeErr = WriteHTMLReport(file, summary, findings)
		default:
			_ = file.Close()
			return generatedPaths, fmt.Errorf("unsupported output format: %s", fmtStr)
		}

		_ = file.Close()

		if writeErr != nil {
			return generatedPaths, fmt.Errorf("failed writing %s report: %w", fmtStr, writeErr)
		}

		generatedPaths = append(generatedPaths, targetPath)
	}

	return generatedPaths, nil
}

