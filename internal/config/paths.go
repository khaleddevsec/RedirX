package config

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"
)

// Subdirectory names inside the RedirX application data directory.
const (
	DirResults   = "results"
	DirReports   = "reports"
	DirLogs      = "logs"
	DirConfig    = "config"
	DirWordlists = "wordlists"
	DirBackups   = "backups"
)

// AppDirs holds resolved absolute paths for all RedirX directories.
type AppDirs struct {
	Root      string
	Results   string
	Reports   string
	Logs      string
	Config    string
	Wordlists string
	Backups   string
}

// GetDataDir determines the root RedirX data directory.
// Priority:
// 1. Explicit override via customDir parameter
// 2. REDIRX_DATA_DIR environment variable
// 3. User home directory: ~/RedirX
func GetDataDir(customDir string) (string, error) {
	if customDir != "" {
		return filepath.Abs(customDir)
	}

	if envDir := os.Getenv("REDIRX_DATA_DIR"); envDir != "" {
		return filepath.Abs(envDir)
	}

	home, err := os.UserHomeDir()
	if err != nil {
		// Fallback to current working directory if user home cannot be determined
		cwd, cwdErr := os.Getwd()
		if cwdErr != nil {
			return "", fmt.Errorf("could not determine home or working directory: %w", err)
		}
		return filepath.Join(cwd, "RedirX"), nil
	}

	return filepath.Join(home, "RedirX"), nil
}

// InitAppDirs ensures the RedirX directory tree exists and returns paths.
func InitAppDirs(customDir string) (*AppDirs, error) {
	rootDir, err := GetDataDir(customDir)
	if err != nil {
		return nil, err
	}

	dirs := &AppDirs{
		Root:      rootDir,
		Results:   filepath.Join(rootDir, DirResults),
		Reports:   filepath.Join(rootDir, DirReports),
		Logs:      filepath.Join(rootDir, DirLogs),
		Config:    filepath.Join(rootDir, DirConfig),
		Wordlists: filepath.Join(rootDir, DirWordlists),
		Backups:   filepath.Join(rootDir, DirBackups),
	}

	allDirs := []string{
		dirs.Root,
		dirs.Results,
		dirs.Reports,
		dirs.Logs,
		dirs.Config,
		dirs.Wordlists,
		dirs.Backups,
	}

	for _, d := range allDirs {
		if err := os.MkdirAll(d, 0755); err != nil {
			return nil, fmt.Errorf("failed to create directory %q: %w", d, err)
		}
	}

	return dirs, nil
}

// GenerateDefaultName creates a timestamped scan name if none was supplied.
func GenerateDefaultName() string {
	return fmt.Sprintf("scan-%s", time.Now().Format("20060102-150405"))
}

// ResolveOutputPath determines the final destination path for a given format.
// It verifies whether the file already exists, and applies overwrite rules:
// - If autoGenerated: picks next free filename (e.g. scan-X_2.txt)
// - If custom and force: overwrites
// - If custom and interactive: prompts user
// - If custom and non-interactive and !force: returns error
func ResolveOutputPath(
	name string,
	format string,
	customOutput string,
	resultsDir string,
	force bool,
	interactive bool,
	autoGenerated bool,
) (string, error) {
	ext := "." + strings.TrimPrefix(strings.ToLower(format), ".")

	var candidatePath string

	if customOutput != "" {
		// Check if customOutput is an existing directory or ends with a slash
		info, err := os.Stat(customOutput)
		if (err == nil && info.IsDir()) || strings.HasSuffix(customOutput, string(os.PathSeparator)) || strings.HasSuffix(customOutput, "/") {
			base := name
			if !strings.HasSuffix(strings.ToLower(base), ext) {
				base += ext
			}
			candidatePath = filepath.Join(customOutput, base)
		} else {
			candidatePath = customOutput
			if !strings.HasSuffix(strings.ToLower(candidatePath), ext) {
				candidatePath += ext
			}
		}
	} else {
		base := name
		if !strings.HasSuffix(strings.ToLower(base), ext) {
			base += ext
		}
		candidatePath = filepath.Join(resultsDir, base)
	}

	candidatePath, err := filepath.Abs(candidatePath)
	if err != nil {
		return "", err
	}

	// Ensure parent directory exists
	if err := os.MkdirAll(filepath.Dir(candidatePath), 0755); err != nil {
		return "", fmt.Errorf("cannot create output directory %s: %w", filepath.Dir(candidatePath), err)
	}

	// Check if file exists
	if _, err := os.Stat(candidatePath); err == nil {
		if force {
			return candidatePath, nil
		}

		if autoGenerated {
			// Find next available unique filename
			dir := filepath.Dir(candidatePath)
			baseNoExt := strings.TrimSuffix(filepath.Base(candidatePath), ext)
			counter := 2
			for {
				newName := fmt.Sprintf("%s_%d%s", baseNoExt, counter, ext)
				testPath := filepath.Join(dir, newName)
				if _, err := os.Stat(testPath); os.IsNotExist(err) {
					return testPath, nil
				}
				counter++
			}
		}

		if interactive {
			fmt.Printf("[!] Warning: Output file %q already exists. Overwrite? (y/N): ", candidatePath)
			reader := bufio.NewReader(os.Stdin)
			ans, _ := reader.ReadString('\n')
			ans = strings.TrimSpace(strings.ToLower(ans))
			if ans == "y" || ans == "yes" {
				return candidatePath, nil
			}
			return "", fmt.Errorf("aborted: destination file %q already exists", candidatePath)
		}

		return "", fmt.Errorf("output file %q already exists (use --force to overwrite)", candidatePath)
	}

	return candidatePath, nil
}

